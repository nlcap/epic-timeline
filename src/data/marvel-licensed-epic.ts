import type { Line, TimelineEntry } from "../types";

// Bulk-wired from src/assets/epic licensed/<Line>.png (Nick dropped in a
// folder of per-line icons). Eagerly globbed so new files just need to
// match a line's name -- no import list to maintain by hand, same pattern
// as classic-marvel-epic.ts's marvelIcon.
const licensedIconModules = import.meta.glob("../assets/epic licensed/*.png", {
  eager: true,
  import: "default",
}) as Record<string, string>;

function licensedIcon(filename: string): string {
  const key = `../assets/epic licensed/${filename}`;
  const url = licensedIconModules[key];
  if (!url) throw new Error(`Missing Licensed icon: ${key}`);
  return url;
}

// Seed data for the "Licensed" Marvel Epic Collection page, pulled from
// Wikipedia's Marvel Epic Collection article:
// https://en.wikipedia.org/wiki/Marvel_Epic_Collection
//
// Covers: Conan (three sub-series), Planet of the Apes, Rom: Spaceknight,
// Micronauts, Aliens, and Star Wars (Legends only -- the modern-era Star
// Wars, Darth Vader, and Kanan Epic Collections are deliberately excluded
// per Nick's request).
//
// Star Wars (Legends) isn't one line -- Marvel itself splits it into 12
// distinct sub-collections (Original Marvel Years, Newspaper Strips, Tales
// of the Jedi, Old Republic, Rise of the Sith, Menace Revealed, Clone Wars,
// Empire, Rebellion, New Republic, Legacy, Infinities), each its own
// Epic Collection numbering and spine color -- so each is its own Line
// here too, matching the Figma reference this feature was built from.
//
// start/end reflect the "Years covered" column (the ORIGINAL COMICS'
// cover-dated years being reprinted, not this Epic Collection line's own
// release date) -- same convention as classic/modern-marvel-epic.ts.
// Several Star Wars sub-lines compile stories wildly out of real
// publication order (e.g. "The Empire" volume 4 spans 1995-2014) -- that's
// not a data error, Dark Horse's original miniseries really did publish in
// that scattered order and Marvel's Epic Collection groups them thematically
// rather than chronologically. Those lines get swimLanes > 1 (computed from
// actual overlap, not guessed) so the overlapping volumes render in
// separate stacked lanes instead of piling on top of each other -- see
// assignLanes/lineHeight in lib/timeline.ts. Adjacent same-numbered volumes
// that only touch at a single shared boundary year (e.g. issue #59 ending
// 1976, #60 starting 1976) are split Q2/Q3 rather than left as a false
// one-quarter overlap.
//
// colorHex is pulled from each Wikipedia table's "Spine lettering" legend,
// translated from color name to hex (Wikipedia gives names like "Orange"/
// "Grey-Blue", not hex values, for this article).
//
// writers/artists come from Wikipedia's Writers/Artists columns. Only the 30
// non-Star Wars volumes have them: the Star Wars (Legends) tables carry no
// creator columns at all (just #/Years/Issues/Pages/Released/ISBN), so those
// sub-lines have no credits to take rather than fabricated ones. releaseDate
// IS available for all 85 -- those tables do have a Released column.
//
// iconUrl: every line's icon, bulk-wired from src/assets/epic licensed/ --
// see licensedIcon above.
//
// King Conan Chronicles Vol. 2 (cancelled -- Marvel lost the Conan license
// in 2022) and Aliens Vol. 5 (blank "Years covered" on Wikipedia) are
// handled per existing convention: cancelled volumes are excluded outright,
// blank-years volumes are estimated from the surrounding volumes and
// flagged inline (see modern-marvel-epic.ts header for the same rule).
//
// coverUrl: flat cover scans from Amazon (m.media-amazon.com), one search
// per ISBN (Amazon returned a single, unambiguous result for every one of
// these -- no title-matching guesswork), upgraded from the search result's
// default thumbnail size to _SL1500_ for a high-res image. Aliens Vol. 5
// has no ISBN yet (unreleased, see above) so it has no cover.
//
// description: Penguin Random House "Book Description" text, copied verbatim
// from each volume's own product page (penguinrandomhouse.com/books/{id}/...),
