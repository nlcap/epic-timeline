// Bulk-wired from src/assets/Marvel/modern/<Character>.png (Nick dropped in a
// folder of per-line icons). Eagerly globbed so new files just need to match a
// line's name -- no import list to maintain by hand. Astonishing X-Men and New
// X-Men share a naming collision in the source folder ("new x-men.png" /
// "new x-men-1.png") -- confirmed with Nick which file is which.
const modernIconModules = import.meta.glob("../assets/Marvel/modern/*.png", {
  eager: true,
  import: "default",
}) as Record<string, string>;

function modernIcon(filename: string): string {
  const key = `../assets/Marvel/modern/${filename}`;
  const url = modernIconModules[key];
  if (!url) throw new Error(`Missing Marvel modern-era icon: ${key}`);
  return url;
}

