// Bulk-wired from src/assets/Marvel/epic classic/<Character>.png (Nick dropped
// in a folder of per-line icons). Eagerly globbed so new files just need to
// match a line's name -- no import list to maintain by hand.
const marvelIconModules = import.meta.glob("../assets/Marvel/epic classic/*.png", {
  eager: true,
  import: "default",
}) as Record<string, string>;

function marvelIcon(filename: string): string {
  const key = `../assets/Marvel/epic classic/${filename}`;
  const url = marvelIconModules[key];
  if (!url) throw new Error(`Missing Marvel icon: ${key}`);
  return url;
}

